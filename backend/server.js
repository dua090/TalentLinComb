require("dotenv").config();

// ======================================================
// ================= DEPENDENCIES =======================
// ======================================================

const express =
  require("express");

const app =
  require("./app");

const connectDB =
  require("./config/db");

// ======================================================
// ================= DATABASE ===========================
// ======================================================

connectDB();

// ======================================================
// ================= STATIC FILES =======================
// ======================================================

app.use(

  "/uploads",

  express.static(
    "uploads"
  )
);

// ======================================================
// ================= PORT ===============================
// ======================================================

const PORT =

  process.env.PORT || 5000;

// ======================================================
// ================= SERVER =============================
// ======================================================

app.listen(

  PORT,

  () => {

    console.log(

      `🚀 Server running on port ${PORT}`
    );
  }
);