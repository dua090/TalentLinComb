const router =
  require("express").Router();

// ======================================================
// ================= MIDDLEWARE =========================
// ======================================================

const auth =
  require(
    "../middleware/authMiddleware"
  );

const allowPermissions =
  require(
    "../middleware/permissionMiddleware"
  );

// ======================================================
// ================= CONTROLLERS ========================
// ======================================================

const {

  getDashboardAnalytics,

} = require(
  "../controllers/analyticsController"
);

// ======================================================
// ================= ANALYTICS ROUTES ===================
// ======================================================

// ======================================================
// ================= DASHBOARD ANALYTICS ================
// ======================================================

router.get(

  "/dashboard",

  auth,

  allowPermissions(
    "insights"
  ),

  getDashboardAnalytics
);

// ======================================================
// ================= EXPORT =============================
// ======================================================

module.exports =
  router;