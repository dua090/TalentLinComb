const express =
  require("express");

const router =
  express.Router();

// ======================================================
// ================= MIDDLEWARE =========================
// ======================================================

const auth =
  require(
    "../middleware/authMiddleware"
  );

const allowPermissions =
  require(
    "../middleware/permissionMiddleware"
  );

// ======================================================
// ================= CONTROLLERS ========================
// ======================================================

const {

  generateCandidateSummary,

} = require(
  "../controllers/aiController"
);

// ======================================================
// ================= AI ROUTES ==========================
// ======================================================

// ======================================================
// ================= AI CANDIDATE SUMMARY ===============
// ======================================================

router.post(

  "/candidate-summary",

  auth,

  allowPermissions(
    "talent_pool"
  ),

  generateCandidateSummary
);

// ======================================================
// ================= EXPORT =============================
// ======================================================

module.exports =
  router;